#!/usr/bin/env bash
# gen_g1.sh — writes the SBY file for G1: the default (oversampled) SPI slave on
# Tiny Tapeout GF26c, proved at the chip's pads through the GF I/O delays, in a
# multiclock time model (2^CPL ticks per core clock: at 25 MHz CPL=1 is a 20 ns
# tick, CPL=2 10 ns, CPL=3 5 ns). Unbounded (PDR), any number of frames.
# Task k<CPL>_m<CPHA>_h<H>_l<L>_s<S>_t<T>_g<G>_i<DI0><DI1>_o<DO0><DO1>_d<SD>[_fb<N>]:
# master phases >= H/L ticks, CS setup >= S, CS high >= G, any longer freely;
# inward pad->port delay DI0..DI1 ticks and outward port->pad DO0..DO1 ticks per
# transition and pin; the master reads MISO SD ticks after its sample edge.
# Names ending in _x are expected to FAIL (they document a limit).
set -eu
# cpl:c:h:l:s:t:g:di0:di1:do0:do1:sd:fb
#   GF26c windows (pad->port <= 5.3 ns, port->pad <= 12.8 ns, see docs/GF26C_IO.md):
#   20 ns ticks i01 o01, 10 ns ticks i01 o02
sweep=${G1_SWEEP:-"1:0:4:4:7:2:12:0:1:0:1:1:1 1:1:4:4:7:2:12:0:1:0:1:1:1
        1:0:4:4:7:2:12:0:1:0:1:1:2 1:1:4:4:7:2:12:0:1:0:1:1:2
        1:0:4:5:7:2:12:0:1:0:1:0:1 1:1:5:4:7:2:12:0:1:0:1:0:1
        1:0:3:5:7:2:12:0:1:0:1:1:1 1:1:5:3:7:2:12:0:1:0:1:1:1
        1:1:4:4:3:2:12:0:1:0:1:1:1 1:0:4:4:6:2:12:0:1:0:1:1:1
        2:0:8:8:12:4:24:0:1:0:2:0:1 2:1:8:8:12:4:24:0:1:0:2:0:1"}
# expected to FAIL (they document limits):
#   CS setup 100 ns in mode 0 (below 3 clocks);
#   SD 0 in the 20 ns model at 160 ns SCLK (the model's 20 ns delay quantum; the
#     10 ns model proves SD 0);
#   a 40 ns (1 clock) SCLK phase at the pad, either mode (rise/fall skew shortens it);
#   40 ns windows both ways (about 3x the GF26c budget) at 160 ns SCLK;
#   10 ns model, outward 0..30 ns, plain master (the MISO margin's upper end)
G1_XFAIL=${G1_XFAIL-"1:0:4:4:5:2:12:0:1:0:1:1:1 1:0:4:4:7:2:12:0:1:0:1:0:1
        1:0:2:6:7:2:12:0:1:0:1:1:1 1:1:6:2:7:2:12:0:1:0:1:1:1 1:0:4:4:7:2:12:0:2:0:2:2:1
        2:0:8:8:12:4:24:0:1:0:3:0:1"}
name() { IFS=: read -r k c h l s t g a b x y d fb <<< "$1"; echo "k${k}_m${c}_h${h}_l${l}_s${s}_t${t}_g${g}_i${a}${b}_o${x}${y}_d${d}$([ "$fb" = 1 ] || echo "_fb$fb")$2"; }
echo "# generated by gen_g1.sh: G1, oversampled slave at the GF26c pads, multiclock tick model (PDR)"
echo "[tasks]"
for p in $sweep; do name "$p" ""; done
for p in $G1_XFAIL; do name "$p" _x; done
echo "cov_m0 cov"
echo "cov_m1 cov"
echo
echo "[options]"
echo "multiclock on"
echo "~cov: mode prove"
echo "cov: mode cover"
echo "cov: depth 120"
echo
echo "[engines]"
echo "~cov: abc scorr; dc2; pdr"
echo "cov: smtbmc yices"
echo
echo "[script]"
for p in $sweep; do
    IFS=: read -r k c h l s t g a b x y d fb <<< "$p"
    echo "$(name "$p" ""): read -define CPL=$k CPHA=$c H=$h L=$l S=$s T=$t G=$g DI0=$a DI1=$b DO0=$x DO1=$y SD=$d FB=$fb"
done
for p in $G1_XFAIL; do
    IFS=: read -r k c h l s t g a b x y d fb <<< "$p"
    echo "$(name "$p" _x): read -define CPL=$k CPHA=$c H=$h L=$l S=$s T=$t G=$g DI0=$a DI1=$b DO0=$x DO1=$y SD=$d FB=$fb"
done
echo "cov_m0: read -define CPL=1 CPHA=0 H=4 L=4 S=6 T=2 G=12 DI0=0 DI1=1 DO0=0 DO1=1 SD=0 FB=1"
echo "cov_m1: read -define CPL=1 CPHA=1 H=4 L=4 S=6 T=2 G=12 DI0=0 DI1=1 DO0=0 DO1=1 SD=0 FB=1"
echo "read -define MASTER_GCLK"
echo "read -formal -sv spi_master_model.v fv_iodelay.v"
echo "read -formal -sv xc_spi_slave_g1.v"
echo "read -formal -sv fv_g1_top.sv"
echo "prep -top fv_g1_top"
echo
echo "[files]"
echo "../tb/spi_master_model.v"
echo "../tb/fv_iodelay.v"
echo "../tb/fv_g1_top.sv"
echo "../build/gen/xc_spi_slave_g1.v"
echo "../props/g1_slave_props.vh"
