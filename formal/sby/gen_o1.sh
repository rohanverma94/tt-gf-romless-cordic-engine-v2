#!/usr/bin/env bash
# gen_o1.sh <orig|new> — writes an SBY file sweeping SPI master timing.
#   orig: the ttsky25a SPI_Slave (O1), one byte per CS frame
#   new:  xc_spi_slave (N1), one or several bytes per CS frame
# Task m<CPHA>_h<H>_l<L>_s<S>[_fb<N>][_t<T>]: master mode, SCLK high/low phase,
# CS setup and CS hold (default 3; the hold follows the last low phase, so the
# real hold after the last edge is L + T) in core clocks (each phase lasts that or one
# more), N bytes per frame.
set -eu
v=$1
if [ "$v" = orig ]; then
    files="../build/gen/spi_slave_o1.v ../props/o1_slave_props.vh"; rd="read -formal spi_slave_o1.v"; def="-D SLAVE_ORIG"
    sweep="0:2:5:5 0:3:5:5 0:4:5:5 0:5:2:5 0:5:3:5 0:5:4:5 0:5:5:1 0:5:5:2 0:5:5:3
           1:1:5:5 1:2:5:5 1:5:1:5 1:5:2:5 1:2:2:5 1:2:1:5 1:1:2:5 1:3:1:5 1:1:3:5 1:5:5:1 1:5:5:2"
else
    files="../build/gen/xc_spi_slave_n1.v ../props/n1_slave_props.vh"; rd="read -formal xc_spi_slave_n1.v"; def=""
    sweep="0:1:5:5 0:2:5:5 0:5:1:5 0:5:2:5 0:1:3:5 0:2:1:5 0:1:2:5 0:2:2:5 0:5:5:1 0:5:5:2 0:5:5:3 0:2:2:5:3 0:5:1:5:1:1
           1:1:5:5 1:2:5:5 1:5:1:5 1:5:2:5 1:1:3:5 1:2:1:5 1:1:2:5 1:2:2:5 1:5:5:1 1:2:2:5:3 1:5:1:5:1:1"
fi
G=5; T=3
[ "$v" = orig ] && CH=5 || CH=2      # cover timing: one that passes
name() { local c=$1 h=$2 l=$3 s=$4 fb=${5:-1} t=${6:-}; echo "m${c}_h${h}_l${l}_s${s}$([ "$fb" = 1 ] || echo "_fb$fb")$([ -z "$t" ] || echo "_t$t")"; }
echo "# generated by gen_o1.sh $v: SPI byte transport against a timed master, any number of frames (PDR)"
echo "# cov_m*: two complete frames are reachable (the timing assumptions are not vacuous)"
echo "[tasks]"
for p in $sweep; do IFS=: read -r c h l s fb t <<< "$p"; name $c $h $l $s $fb $t; done
echo "cov_m0 cov"
echo "cov_m1 cov"
echo
echo "[options]"
echo "~cov: mode prove"
echo "cov: mode cover"
echo "cov: depth $(( 2 * (G + 1 + 5 + 1 + 8 * (CH + CH + 2) + T + 1) + 20 ))"
echo
echo "[engines]"
echo "~cov: abc pdr"
echo "cov: smtbmc yices"
echo
echo "[script]"
for p in $sweep; do
    IFS=: read -r c h l s fb t <<< "$p"; fb=${fb:-1}
    echo "$(name $c $h $l $s $fb $t): read -define CPHA=$c H=$h L=$l S=$s T=${t:-$T} G=$G FB=$fb NFRAMES=2"
done
echo "cov_m0: read -define CPHA=0 H=$CH L=$CH S=5 T=$T G=$G FB=1 NFRAMES=2"
echo "cov_m1: read -define CPHA=1 H=$CH L=$CH S=5 T=$T G=$G FB=1 NFRAMES=2"
echo "read -formal spi_master_model.v"
echo "$rd"
echo "read -formal -sv $def fv_spi_top.sv"
echo "prep -top fv_spi_top"
echo "setundef -zero"
echo
echo "[files]"
echo "../tb/spi_master_model.v"
echo "../tb/fv_spi_top.sv"
for f in $files; do echo "$f"; done
