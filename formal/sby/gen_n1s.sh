#!/usr/bin/env bash
# gen_n1s.sh — writes the SBY file for N1S: the SCLK-domain SPI slave against a
# timed master, in a multiclock time model (1 tick = 1/4 core clock = 2.5 ns at
# 100 MHz). Unbounded (PDR), any number of frames.
# Task m<CPHA>_h<H>_l<L>_s<S>_t<T>_g<G>[_fb<N>]: SCLK high/low >= H/L ticks, CS
# low -> first edge >= S, after the last low phase >= T more before CS rises
# (CS hold after the last edge >= L + T), CS high >= G, N bytes per frame; every
# phase that long or any longer, chosen freely (STRETCH), so a PASS holds for
# every slower master too. cov_m*: two complete frames are reachable.
set -eu
sweep=${N1S_SWEEP:-"0:3:3:12:1:24 0:3:3:8:1:24 0:3:3:12:1:16 0:3:3:12:1:12 0:3:1:12:1:24 0:2:2:12:1:24 0:1:1:12:1:24 0:3:3:12:1:24:2 0:1:2:12:1:24:2
       1:3:3:8:1:24 1:3:3:4:1:24 1:3:3:8:1:16 1:3:3:8:1:12 1:3:1:8:1:24 1:2:2:8:1:24 1:1:1:8:1:24 1:3:3:8:1:24:2 1:2:1:8:1:24:2"}
name() { local c=$1 h=$2 l=$3 s=$4 t=$5 g=$6 fb=${7:-1}; echo "m${c}_h${h}_l${l}_s${s}_t${t}_g${g}$([ "$fb" = 1 ] || echo "_fb$fb")"; }
echo "# generated by gen_n1s.sh: N1S, SCLK-domain slave, multiclock tick model (PDR)"
echo "[tasks]"
for p in $sweep; do IFS=: read -r c h l s t g fb <<< "$p"; name $c $h $l $s $t $g $fb; done
echo "cov_m0 cov"
echo "cov_m1 cov"
echo
echo "[options]"
echo "multiclock on"
echo "~cov: mode prove"
echo "cov: mode cover"
echo "cov: depth 260"
echo
echo "[engines]"
echo "~cov: abc scorr; dc2; pdr"          # scorr merges the property copies of design registers: PDR then converges on multi-byte frames
echo "cov: smtbmc yices"
echo
echo "[script]"
for p in $sweep; do
    IFS=: read -r c h l s t g fb <<< "$p"; fb=${fb:-1}
    echo "$(name $c $h $l $s $t $g $fb): read -define CPHA=$c H=$h L=$l S=$s T=$t G=$g FB=$fb"
done
echo "cov_m0: read -define CPHA=0 H=3 L=3 S=12 T=1 G=24 FB=1"
echo "cov_m1: read -define CPHA=1 H=3 L=3 S=8 T=1 G=24 FB=1"
echo "read -define XC_FV_META MASTER_GCLK"
echo "read -formal -sv spi_master_model.v xc_meta.v"
echo "read -formal -sv xc_spi_slave_sclk_n1s.v"
echo "read -formal -sv fv_n1s_top.sv"
echo "prep -top fv_n1s_top"
echo
echo "[files]"
echo "../tb/spi_master_model.v"
echo "../tb/fv_n1s_top.sv"
echo "../../src/xc_meta.v"
echo "../build/gen/xc_spi_slave_sclk_n1s.v"
echo "../props/n1s_slave_props.vh"
